def law_label(law_id):
    return LAW.get(law_id) or law_id.replace("-", " ")

def author_label(source_id, registry_title=""):
    if source_id in AUTH:
        return AUTH[source_id]
    guess = registry_title.split(",")[0].strip() if registry_title else ""
    return (guess or "Unknown author", "")


def headline(name, kind):
    """Headline of a finding: individuals give an expert statement, organisations a statement."""
    if kind.startswith("speaker"):                      # a speaker recorded in a hearing transcript
        return "Statement at the " + name[0].lower() + name[1:]
    return ("Expert statement by " if kind == "individual expert" else "Statement by ") + name
